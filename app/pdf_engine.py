"""Narrow, typed declarations for the PyMuPDF features used by PDF analysis.

PyMuPDF ships without Python typing metadata. These protocols describe the real
library objects at that dependency seam; they do not wrap or emulate the engine.
"""
from collections.abc import Iterator
from types import TracebackType
from typing import Protocol, TypedDict, cast

import pymupdf


class LayerControl(TypedDict):
    number: int
    on: int


class Rectangle(Protocol):
    @property
    def width(self) -> float: ...
    @property
    def height(self) -> float: ...
    def __iter__(self) -> Iterator[float]: ...


class Pixmap(Protocol):
    @property
    def samples(self) -> bytes: ...
    @property
    def width(self) -> int: ...
    @property
    def height(self) -> int: ...
    def tobytes(self, output: str = "png") -> bytes: ...


class Page(Protocol):
    @property
    def rect(self) -> Rectangle: ...
    @property
    def mediabox(self) -> Rectangle: ...
    @property
    def cropbox(self) -> Rectangle: ...
    @property
    def rotation(self) -> int: ...
    def get_label(self) -> str: ...
    def get_pixmap(self, *, matrix: object, colorspace: object, alpha: bool, annots: bool) -> Pixmap: ...


class Document(Protocol):
    def __getitem__(self, index: int) -> Page: ...
    def __enter__(self) -> "Document": ...
    def __exit__(self, kind: type[BaseException] | None, value: BaseException | None,
                 traceback: TracebackType | None) -> None: ...
    def get_ocgs(self) -> dict[int, object]: ...
    def pdf_catalog(self) -> int: ...
    def xref_get_key(self, xref: int, key: str) -> tuple[str, str]: ...
    def xref_object(self, xref: int) -> str: ...
    def xref_set_key(self, xref: int, key: str, value: str) -> None: ...
    def tobytes(self) -> bytes: ...
    def close(self) -> None: ...
    def layer_ui_configs(self) -> list[LayerControl]: ...
    def set_layer_ui_config(self, number: int, action: int) -> None: ...


class Engine(Protocol):
    VersionBind: str
    csRGB: object
    def open(self, filename: str | None = None, *, stream: bytes | None = None,
             filetype: str | None = None) -> Document: ...
    def Matrix(self, x: float, y: float) -> object: ...


engine = cast(Engine, pymupdf)
